static HAL_StatusTypeDef OLED_WriteCommands(const uint8_t *cmds, uint16_t count)
{
    uint8_t packet[32];
    uint16_t i;

    if (cmds == NULL || count > 31U) {
        return HAL_ERROR;
    }
    packet[0] = 0x00U; /* 后续字节全部是命令 */
    for (i = 0U; i < count; ++i) {
        packet[i + 1U] = cmds[i];
    }
    return HAL_I2C_Master_Transmit(&hi2c1, OLED_I2C_ADDR,
                                   packet, (uint16_t)(count + 1U), OLED_I2C_TIMEOUT_MS);
}

HAL_StatusTypeDef OLED_Init(void)
{
    /* 仅对应常见 SSD1306 128x64 模块（内部电荷泵供电）。 */
    static const uint8_t init_commands[] = {
        0xAE,       /* 关闭显示 */
        0xD5, 0x80, /* 显示时钟 */
        0xA8, 0x3F, /* 1/64 扫描 */
        0xD3, 0x00, /* 显示偏移 */
        0x40,       /* 起始扫描行 */
        0x8D, 0x14, /* 使能内部电荷泵 */
        0x20, 0x02, /* 页寻址模式 */
        0xA1,       /* SEG 映射 */
        0xC8,       /* COM 反向扫描 */
        0xDA, 0x12, /* COM 引脚设置 (128x64) */
        0x81, 0xCF, /* 对比度 */
        0xD9, 0xF1, /* 预充电周期 */
        0xDB, 0x40, /* VCOMH */
        0xA4,       /* 使用显存内容 */
        0xA6,       /* 正常显示 */
        0xAF        /* 打开显示 */
    };
    HAL_StatusTypeDef status;

    HAL_Delay(100U); /* 请在启动 RTOS 前调用 OLED_Init */
    status = HAL_I2C_IsDeviceReady(&hi2c1, OLED_I2C_ADDR, 3U, 100U);
    if (status != HAL_OK) {
        return status;
    }
    status = OLED_WriteCommands(init_commands, (uint16_t)sizeof(init_commands));
    if (status != HAL_OK) {
        return status;
    }
    OLED_Clear();
    return OLED_Update();
}

void OLED_Clear(void)
{
    memset(s_framebuffer, 0, sizeof(s_framebuffer));
}

void OLED_DrawPixel(uint8_t x, uint8_t y, uint8_t on)
{
    uint16_t index;
    uint8_t mask;

    if (x >= OLED_WIDTH || y >= OLED_HEIGHT) {
        return;
    }
    index = (uint16_t)((uint16_t)(y / 8U) * OLED_WIDTH + x);
    mask = (uint8_t)(1U << (y & 7U));
    if (on != 0U) {
        s_framebuffer[index] |= mask;
    } else {
        s_framebuffer[index] &= (uint8_t)~mask;
    }
}

void OLED_DrawChar(uint8_t x, uint8_t y, char ch)
{
    uint8_t column, row, value;
    uint8_t glyph;

    if ((unsigned char)ch < 0x20U || (unsigned char)ch > 0x7EU) {
        ch = '?';
    }
    glyph = (uint8_t)((unsigned char)ch - 0x20U);
    for (column = 0U; column < 6U; column++) {
        value = (column < 5U) ? s_font5x7[glyph][column] : 0U;
        for (row = 0U; row < 8U; row++) {
            OLED_DrawPixel((uint8_t)(x + column), (uint8_t)(y + row),
                           (uint8_t)((value >> row) & 1U));
        }
    }
}

void OLED_DrawString(uint8_t x, uint8_t y, const char *text)
{
    if (text == NULL) {
        return;
    }
    while (*text != '\0') {
        if (*text == '\n') {
            x = 0U;
            y = (uint8_t)(y + 8U);
            ++text;
            continue;
        }
        if ((uint16_t)x + 6U > OLED_WIDTH) {
            x = 0U;
            y = (uint8_t)(y + 8U);
        }
        if ((uint16_t)y + 8U > OLED_HEIGHT) {
            break;
        }
        OLED_DrawChar(x, y, *text++);
        x = (uint8_t)(x + 6U);
    }
}

HAL_StatusTypeDef OLED_Update(void)
{
    uint8_t packet[1U + OLED_WIDTH];
    uint8_t page;
    uint16_t column;
    HAL_StatusTypeDef status;
    const uint8_t page_prefix[3] = {0xB0U, 0x00U, 0x10U};
    uint8_t command[3];

    packet[0] = 0x40U; /* 后续字节全部是显存数据 */
    for (page = 0U; page < (OLED_HEIGHT / 8U); ++page) {
        command[0] = (uint8_t)(page_prefix[0] + page);
        command[1] = page_prefix[1];
        command[2] = page_prefix[2];
        status = OLED_WriteCommands(command, 3U);
        if (status != HAL_OK) {
            return status;
        }
        for (column = 0U; column < OLED_WIDTH; column++) {
            packet[column + 1U] = s_framebuffer[(uint16_t)(page * OLED_WIDTH + column)];
        }
        status = HAL_I2C_Master_Transmit(&hi2c1, OLED_I2C_ADDR,
                                         packet, (uint16_t)sizeof(packet), OLED_I2C_TIMEOUT_MS);
        if (status != HAL_OK) {
            return status;
        }
    }
    return HAL_OK;
}
